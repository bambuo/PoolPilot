namespace PoolPilot.Domain.Enums;

/// <summary>
/// 跟单员的执行模式。
///
/// 它是**跟单员自身的属性**，不是界面上的一个开关：同一个带单员下可以同时挂着
/// 纸面跟单员与（将来的）实盘跟单员，各自独立记账。前端常量表达不了
/// "这个账户是纸面、那个是实盘"，所以模式必须存在实体上。
/// </summary>
public enum CopyMode
{
    /// <summary>纸面模式：不发送任何真实订单，全部按真实盘口模拟成交并记账。</summary>
    Paper = 0,

    /// <summary>
    /// 实盘模式：预留。当前没有可用的下单签名器（纯 .NET 环境签不了 Lighter 的订单），
    /// 配置接口会拒绝创建，实体字段与判别逻辑先就位。
    /// </summary>
    Live = 1,
}
