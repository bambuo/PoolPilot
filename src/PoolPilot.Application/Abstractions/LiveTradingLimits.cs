namespace PoolPilot.Application.Abstractions;

/// <summary>
/// 实盘执行侧的配置。
///
/// **不设名义额上限**（曾经有过"单笔 ≤20 / 日内 ≤50 / 总仓位 ≤100 USDT"那一套，已按使用者要求撤掉）：
/// 规模由**标准跟单口径**决定——比例复制，目标名义额 = 池子名义额 × (本金 ÷ 池子权益)。
/// 也就是说风险天然被本金封顶：能亏的上限就是投进去的钱，不需要再叠一层人为限额。
///
/// 撤掉上限之后，真正拦住"下不出去的单"的是**交易所自己的规格**：
/// 最小下单量、最小名义额、可用保证金（币安以 -2019/-4164 拒单）。
/// 这些不是可选的限额，而是交易所的硬规则，所以本地仍会先算一遍并**如实记录跳过原因**——
/// 让币安拒单也能跑通，但那样我们只知道"失败了"，不知道"差多少"。
///
/// ⚠️ 剩下这两个开关的分工：
/// <list type="bullet">
///   <item><see cref="Enabled"/> —— 实盘总闸。关掉后任何下单路径直接拒绝（暂停用）。</item>
///   <item><see cref="Leverage"/> —— 下单前为该合约设定的杠杆。它决定**占用多少保证金**，
///     不是"要多冒险"：同样 20 USDT 名义，10 倍占 2 USDT、5 倍占 4 USDT。占用越少，
///     留给价格波动的缓冲越多。它同时是交易所侧的名义额天花板（可用保证金 × 杠杆）。</item>
/// </list>
/// </summary>
public sealed class LiveTradingLimits
{
    /// <summary>实盘总开关。关掉后任何下单路径直接拒绝。</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>下单前为该合约设定的杠杆。</summary>
    public int Leverage { get; set; } = 10;
}
